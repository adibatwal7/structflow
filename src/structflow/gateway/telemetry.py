"""Telemetry: one JSON log line and a few Prometheus metrics per inference request.

The log line answers "what happened to request X?" (search by request_id).
The metrics answer "how is the service doing?" (rates, latencies, fallbacks),
scraped from GET /metrics by Prometheus or read by hand.

The middleware wraps POST /v1/infer only. The endpoint and the error handlers leave
notes in the request state (the task, the response, the error code), and the
middleware turns them into one record when the request is over, whatever happened.
"""

import json
import logging
import time
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from typing import Any, Final

from fastapi import APIRouter, Request, Response
from prometheus_client import (
    CONTENT_TYPE_LATEST,
    CollectorRegistry,
    Counter,
    Histogram,
    generate_latest,
)
from starlette.types import ASGIApp, Message, Receive, Scope, Send

from structflow.schemas.responses import InferenceResponse

logger = logging.getLogger("structflow.requests")
SECONDS: Final = (0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10, 30, 60)


@dataclass(frozen=True, slots=True)
class RequestRecord:
    ts: str
    request_id: str | None
    status: int
    total_ms: float
    task: str | None = None
    route: str | None = None
    route_trail: tuple[str, ...] = ()
    degraded: bool = False
    error: str | None = None
    prompt_tokens: int = 0
    completion_tokens: int = 0
    ttft_ms: float | None = None
    tpot_ms: float | None = None

    def to_json(self) -> str:
        fields = {k: v for k, v in asdict(self).items() if v is not None and v != ()}
        return json.dumps(fields, separators=(",", ":"))


def record_from(state: dict[str, Any], status: int, total_ms: float) -> RequestRecord:
    """Build the record from the notes the endpoint and error handlers left."""
    response = state.get("inference")
    error = state.get("error_code")
    if status >= 500 and error is None and not isinstance(response, InferenceResponse):
        error = "internal_error"  # a crash: no handler got to leave a note
    base: dict[str, Any] = {
        "ts": datetime.now(UTC).isoformat(timespec="milliseconds"),
        "request_id": state.get("request_id"),
        "status": status,
        "total_ms": round(total_ms, 3),
        "task": state.get("task"),
        "error": error,
    }
    if isinstance(response, InferenceResponse):
        base |= {
            "route": response.route.value,
            "route_trail": tuple(r.value for r in response.route_trail),
            "degraded": response.degraded,
            "prompt_tokens": response.usage.prompt_tokens,
            "completion_tokens": response.usage.completion_tokens,
            "ttft_ms": response.timings.ttft_ms,
            "tpot_ms": response.timings.tpot_ms,
        }
    return RequestRecord(**base)


class Telemetry:
    """The metrics. Each app gets its own registry, so tests don't share counters."""

    def __init__(self) -> None:
        self.registry = CollectorRegistry()
        self.requests = Counter(
            "structflow_requests",
            "Inference requests, by task, route and outcome (ok or an error code)",
            ["task", "route", "outcome"],
            registry=self.registry,
        )
        self.latency = Histogram(
            "structflow_request_seconds",
            "Time to answer an inference request, end to end",
            ["task", "route"],
            buckets=SECONDS,
            registry=self.registry,
        )
        self.ttft = Histogram(
            "structflow_ttft_seconds",
            "Time to the first generated token (LLM routes only)",
            ["route"],
            buckets=SECONDS,
            registry=self.registry,
        )
        self.tokens = Counter(
            "structflow_generated_tokens",
            "Tokens generated by the LLM",
            ["route"],
            registry=self.registry,
        )
        self.fallbacks = Counter(
            "structflow_fallbacks",
            "Requests a cheaper route could not serve, answered by a later one",
            ["task"],
            registry=self.registry,
        )

    def record(self, rec: RequestRecord) -> None:
        task = rec.task or "unknown"
        route = rec.route or "none"
        outcome = rec.error or "ok"
        self.requests.labels(task, route, outcome).inc()
        self.latency.labels(task, route).observe(rec.total_ms / 1000)
        if rec.ttft_ms is not None:
            self.ttft.labels(route).observe(rec.ttft_ms / 1000)
        if rec.completion_tokens > 0:
            self.tokens.labels(route).inc(rec.completion_tokens)
        if len(rec.route_trail) > 1:
            self.fallbacks.labels(task).inc()
        logger.info(rec.to_json())

    def exposition(self) -> bytes:
        return generate_latest(self.registry)


class TelemetryMiddleware:
    def __init__(
        self, app: ASGIApp, telemetry: Telemetry, path: str = "/v1/infer"
    ) -> None:
        self.app = app
        self.telemetry = telemetry
        self.path = path

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http" or scope["path"] != self.path:
            await self.app(scope, receive, send)
            return
        started = time.perf_counter()
        status = 500  # if no response ever starts, it was a crash

        async def watch(message: Message) -> None:
            nonlocal status
            if message["type"] == "http.response.start":
                status = message["status"]
            await send(message)

        try:
            await self.app(scope, receive, watch)
        finally:  # runs on success, on handled errors, and on crashes
            total_ms = (time.perf_counter() - started) * 1000
            self.telemetry.record(record_from(scope.get("state", {}), status, total_ms))


def configure_request_log(level: str) -> None:
    """Print each request record as a bare JSON line (easy for log tools to read)."""
    logger.setLevel(level)
    if not logger.handlers:
        handler = logging.StreamHandler()
        handler.setFormatter(logging.Formatter("%(message)s"))
        logger.addHandler(handler)


router = APIRouter(tags=["telemetry"])


@router.get("/metrics", include_in_schema=False)
async def metrics(request: Request) -> Response:
    telemetry: Telemetry = request.app.state.telemetry
    return Response(telemetry.exposition(), media_type=CONTENT_TYPE_LATEST)
